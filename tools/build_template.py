#!/usr/bin/env python3
"""Build switch/labroom.template.yaml from docs/agents/*.md and docs/room_instructions.txt.

The template creates (or reuses) the seven LabRoom agents and the lab room in one
run from Switch Console > Templates > Import template, then Use. Edit the
instruction files, not the YAML, and rebuild.

Usage:
    python tools/build_template.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

AGENTS = [
    # name, alias, model, effort, description
    ("coordinator.lab", "coordinator", "claude-haiku-5-5", None,
     "Routes work in the TrailNet lab room and answers questions from the record. Stays quiet otherwise."),
    ("scribe.lab", "scribe", "claude-opus-5-5", "high",
     "Turns meeting transcripts into a summary, PROPOSED decisions for the PI to approve, and a task list."),
    ("librarian.lab", "librarian", "claude-sonnet-5-5", None,
     "Scores papers 0 to 10 against the TrailNet brief and tags the student whose work they touch."),
    ("reporter.lab", "reporter", "claude-opus-5-5", None,
     "Makes the weekly lab board from daily logs, commits and tasks."),
    ("logbook.lab", "logbook", "claude-haiku-5-5", None,
     "Turns a student's direct message about their day into a daily log entry they approve before it is shared."),
    ("auditor.lab", "auditor", "claude-opus-5-5", None,
     "Audits status and risks for the PI: who did what, what is blocked, what needs a decision."),
    ("organizer.lab", "organizer", "claude-sonnet-5-5", None,
     "Acts for the PI: announcements, meeting notices with agendas, reminders, transcript requests, private messages."),
]

MEMBERS = ["maya.chen", "priya.nair", "lucas.moreno", "sofia.alvarez", "omar.haddad", "wei.zhang"]

KICKOFF = (
    "@coordinator this is the TrailNet lab room. The room instructions hold the project brief. "
    "@scribe handles meetings, @librarian papers, @reporter the weekly lab board, @logbook daily logs "
    "by direct message, @auditor status and risks, @organizer announcements and meetings. "
    "Each of you: introduce yourself in one line."
)


def block(text, indent):
    pad = " " * indent
    return "|\n" + "\n".join((pad + line) if line.strip() else "" for line in text.strip().splitlines())


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    room_instructions = (ROOT / "docs" / "room_instructions.txt").read_text(encoding="utf-8")
    out = [
        "# LabRoom: a research group's AI workstation in chat.",
        "# Generated by tools/build_template.py from docs/agents/*.md. Edit those files, then rebuild.",
        "version: 1",
        "params:",
        "  room_name:",
        "    type: string",
        "    label: Room name",
        "    default: trailnet",
        "  bridge:",
        "    type: bridge",
        "    default: [Mattermost, $first]",
        "  workspace:",
        "    type: directory",
        "    label: Your labroom clone (agents read seed/, trailnet/ and tools/ there)",
        "    default: \"{$agents_dir}/labroom\"",
        "agents:",
    ]
    for name, alias, model, effort, description in AGENTS:
        instructions = (ROOT / "docs" / "agents" / f"{alias}.md").read_text(encoding="utf-8")
        out += [
            f"  - name: {name}",
            f"    description: {q(description)}",
            "    provider: claude",
            "    location: local",
            "    directory: \"{workspace}\"",
            f"    model: {model}",
        ]
        if effort:
            out += ["    advanced_config:", f"      effort: {effort}"]
        out += [
            "    addressing: anyone",
            "    allow_existing: true",
            "    instructions: " + block(instructions, 6),
        ]
    out += [
        "room:",
        "  name: \"{room_name}\"",
        "  description: TrailNet research lab room - meetings, papers, daily logs, progress and audits.",
        "  bridge: \"{bridge}\"",
        "  channel_type: channel_public",
        "  instructions: " + block(room_instructions, 4),
        "  agents: [" + ", ".join(a[0] for a in AGENTS) + "]",
        "  users: [\"{$creator}\", " + ", ".join(MEMBERS) + "]",
        "  aliases:",
    ]
    out += [f"    {name}: {alias}" for name, alias, *_ in AGENTS]
    out += ["kickoff: " + block(KICKOFF, 2), ""]
    path = ROOT / "switch" / "labroom.template.yaml"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)} ({len(AGENTS)} agents, {len(MEMBERS)} members)")


if __name__ == "__main__":
    main()
